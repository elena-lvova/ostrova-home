const $ = (s) => document.querySelector(s);
const nav = $('#mainNav'), mega = $('#mega'), megaInner = $('#megaInner');
let V = 'aud', openIdx = -1;

function renderNav() {
  nav.innerHTML = NAV[V].map((n, i) => `<li class="main-nav__item" data-i="${i}"><button aria-expanded="false" aria-controls="mega">${n.t}</button></li>`).join('');
  nav.querySelectorAll('.main-nav__item').forEach((li) => {
    const i = +li.dataset.i;
    li.addEventListener('mouseenter', () => openMega(i));
    li.querySelector('button').addEventListener('click', () => (openIdx === i ? closeMega() : openMega(i)));
  });
}
function openMega(i) {
  const n = NAV[V][i]; openIdx = i;
  megaInner.innerHTML = `<div class="mega__intro"><h3>${n.t}</h3><a class="all-button" href="#">Перейти в раздел</a></div>
    <div class="mega__cols">${n.cols.map(([h, items]) => `<div class="mega__col">${h ? `<h4>${h}</h4>` : '<h4>&nbsp;</h4>'}<ul>${items.map((x) => `<li><a href="#">${x}</a></li>`).join('')}</ul></div>`).join('')}</div>`;
  mega.hidden = false;
  nav.querySelectorAll('.main-nav__item').forEach((li) => { const on = +li.dataset.i === i; li.classList.toggle('is-open', on); li.querySelector('button').setAttribute('aria-expanded', on); });
}
function closeMega() { mega.hidden = true; openIdx = -1; nav.querySelectorAll('.main-nav__item').forEach((li) => { li.classList.remove('is-open'); li.querySelector('button').setAttribute('aria-expanded', 'false'); }); }
$('.site-header').addEventListener('mouseleave', closeMega);
document.addEventListener('keydown', (e) => { if (e.key === 'Escape') closeMega(); });

